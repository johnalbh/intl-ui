function c(
  name: string,
  iso2: string,
  iso3: string,
  dialCode: string,
  region: string,
  subregion: string,
  format?: string,
  priority: number = 0,
  areaCodes?: string[],
): Country {
  const capital = CAPITALS[iso2];
  if (!capital) {
    throw new Error(`Missing capital for country "${name}" (iso2="${iso2}")`);
  }
  return {
    name,
    iso2: iso2 as Country['iso2'],
    iso3,
    dialCode,
    format,
    priority,
    areaCodes,
    flag: iso2ToFlag(iso2),
    capital,
    region,
    subregion,
  };
}

