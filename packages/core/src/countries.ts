/**
 * Find a country by ISO2 code.
 */
export function getCountryByIso2(iso2: string): Country | undefined {
  return countries.find((c) => c.iso2 === iso2.toLowerCase());
}

/**
 * Find a country by ISO3 code.
 */
export function getCountryByIso3(iso3: string): Country | undefined {
  return countries.find((c) => c.iso3 === iso3.toLowerCase());
}

/**
 * Find countries by dial code. Returns multiple for shared codes (e.g., +1).
 */
export function getCountriesByDialCode(dialCode: string): Country[] {
  return countries.filter((c) => c.dialCode === dialCode);
}
